template <std::size_t N>
constexpr auto const& nodes()
{
    static_assert(N == 16 || N == 32 || N == 64 || N == 128,
                  "supported Gauss-Legendre orders are 16, 32, 64, and 128");
    if constexpr (N == 16) return GL16_X;
    else if constexpr (N == 32) return GL32_X;
    else if constexpr (N == 64) return GL64_X;
    else return GL128_X;
}

template <std::size_t N>
constexpr auto const& weights()
{
    static_assert(N == 16 || N == 32 || N == 64 || N == 128,
                  "supported Gauss-Legendre orders are 16, 32, 64, and 128");
    if constexpr (N == 16) return GL16_W;
    else if constexpr (N == 32) return GL32_W;
    else if constexpr (N == 64) return GL64_W;
    else return GL128_W;
}

// Integrate f over [a,b] with a compile-time-selected fixed rule.  Templating
// the callable keeps this suitable for small hot-path lambdas: no allocation,
// type erasure, or virtual dispatch is introduced.
template <std::size_t N, typename F, typename T>
inline T integrate(F&& f, T a, T b)
{
    T const mid  = T{0.5} * (a + b);
    T const half = T{0.5} * (b - a);
    T sum = T{0};
    auto const& x = nodes<N>();
    auto const& w = weights<N>();
    for (std::size_t i = 0; i < N; ++i)
        sum += static_cast<T>(w[i])
             * static_cast<T>(f(mid + half * static_cast<T>(x[i])));
    return half * sum;
}

